#!/usr/bin/env python3
"""Build the deterministic, flat client bundle embedded in both Windows EXEs."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bundle_files():
    files = {name: (ROOT / "tools" / name).read_bytes() for name in (
        "dropbear_mcp.py", "windows_exec.py", "requirements-mcp.txt",
        "session_screenshot.ps1", "session_display.ps1")}
    files["SKILL.md"] = (ROOT / "skills/dropbear-win/SKILL.md").read_bytes().replace(
        b"references/mcp.md", b"mcp-reference.md")
    files["mcp-reference.md"] = (ROOT / "skills/dropbear-win/references/mcp.md").read_bytes().replace(
        b"tools/dropbear_mcp.py", b"dropbear_mcp.py").replace(
        b"tools/requirements-mcp.txt", b"requirements-mcp.txt")
    files["agent-mcp.md"] = (ROOT / "docs/installed-agent-mcp.md").read_bytes()
    files["mcp.json"] = (ROOT / "src/windows/agent-mcp.json").read_bytes()
    # Hash the shipped bytes, including the flattened Markdown references.
    manifest = {"schema_version": 1, "layout": "flat", "embedded": True,
                "files": [{"name": name, "size": len(data),
                           "sha256": hashlib.sha256(data).hexdigest()}
                          for name, data in files.items()]}
    files["bundle-manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    return files


def generate_header(files):
    parts = ["/* Generated by scripts/embed-agent-bundle.py; do not edit. */\n"]
    for i, data in enumerate(files.values()):
        if b"\0" in data:
            raise ValueError("Agent resources must be NUL-free text")
        # Numeric bytes avoid compiler encoding, escape and string-length limits.
        values = [str(byte) for byte in data + b"\0"]
        rows = [",".join(values[n:n + 24]) for n in range(0, len(values), 24)]
        parts.append(f"static const char bundle_data_{i}[] = {{\n" + ",\n".join(rows) + "\n};\n")
    parts.append("static const struct bundle_file bundle_files[] = {\n")
    for i, (name, data) in enumerate(files.items()):
        parts.append(f'    {{L"{name}", "{name}", bundle_data_{i}, {len(data)}}},\n')
    parts.append("};\n")
    return "".join(parts).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    content = generate_header(bundle_files())
    args.header.parent.mkdir(parents=True, exist_ok=True)
    if not args.header.exists() or args.header.read_bytes() != content:
        args.header.write_bytes(content)


if __name__ == "__main__":
    main()
